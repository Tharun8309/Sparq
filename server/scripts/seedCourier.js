async function seedCourier() {
  try {
    await connectDB();
    console.log(`[Seed] Idempotent bulk insertion of ${pincodes.length} courier pincodes...`);

    const operations = pincodes.map(pin => ({
      updateOne: {
        filter: { pincode: pin },
        update: { $set: { pincode: pin, isServiceable: true } },
        upsert: true
      }
    }));

    const result = await CourierPincode.bulkWrite(operations);
    console.log(`[Seed] Courier Pincodes Upserted: ${result.upsertedCount}, Modified: ${result.modifiedCount}`);
    process.exit(0);
  } catch (err) {
    console.error('[Seed Courier Error]:', err.message);
    process.exit(1);
  }
}

seedCourier();
